#!/usr/bin/env node
/**
 * Generate ui/i18n.js from the dictionary files.
 *
 *   ui/i18n.en.json         whole strings — exact matches, the bulk of the panel
 *   ui/i18n.words.json      nouns and units — for text that arrives interpolated
 *   ui/i18n.connectors.json function words — only after a strong term matched
 *   scripts/i18n-template.js the runtime (walking, observer, locale switch)
 *
 * The output is committed so the panel works straight from a clone, with no
 * build step. Run this after editing a dictionary, then check the gaps:
 *
 *   npm run i18n && npm run i18n:check
 */
import fs from 'node:fs';
import path from 'node:path';
import { STUDIO_ROOT } from '../lib/paths.mjs';

const read = (rel) => JSON.parse(fs.readFileSync(path.join(STUDIO_ROOT, rel), 'utf8'));
const phrases = read('ui/i18n.en.json');
const words = read('ui/i18n.words.json');
const connectors = read('ui/i18n.connectors.json');

for (const [name, dict] of [['ui/i18n.en.json', phrases], ['ui/i18n.words.json', words], ['ui/i18n.connectors.json', connectors]]) {
  const keys = Object.keys(dict);
  if (!keys.length) throw new Error(`${name} is empty`);
  const dupes = keys.filter((k, i) => keys.indexOf(k) !== i);
  if (dupes.length) throw new Error(`${name} has duplicate keys after normalisation: ${dupes.slice(0, 3).join(', ')}`);
  const untranslated = keys.filter((k) => dict[k] && /[\u0600-\u06FF]/.test(dict[k]));
  if (untranslated.length)
    throw new Error(`${name} still contains Persian: ${untranslated.slice(0, 3).join(' | ')}`);
}

const body = fs
  .readFileSync(path.join(STUDIO_ROOT, 'scripts', 'i18n-template.js'), 'utf8')
  .replace('%%PHRASES%%', JSON.stringify(phrases, null, 2))
  .replace('%%WORDS%%', JSON.stringify(words, null, 2))
  .replace('%%CONNECTORS%%', JSON.stringify(connectors, null, 2))
  .replace('/* generated */', `/* generated by scripts/build-i18n.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand */`);

if (body.includes('%%')) throw new Error('template tokens were not substituted');
fs.writeFileSync(path.join(STUDIO_ROOT, 'ui', 'i18n.js'), body);
console.log(
  `ui/i18n.js — ${Object.keys(phrases).length} phrases, ${Object.keys(words).length} terms, ${Object.keys(connectors).length} connectors`,
);
